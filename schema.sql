-- 1) Táblák -------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('member','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.news (
  id bigint generated by default as identity primary key,
  category text not null default 'KÖZÖSSÉG' check (char_length(category) between 1 and 40),
  title text not null check (char_length(title) between 1 and 100),
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);

create index if not exists news_created_at_idx on public.news (created_at desc);

-- 2) RLS bekapcsolása ---------------------------------------
alter table public.profiles enable row level security;
alter table public.news enable row level security;

-- 3) Segédfüggvény: a bejelentkezett felhasználó admin-e? ----
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = (select auth.uid())
      and p.role = 'admin'
  );
$$;

revoke execute on function public.is_admin() from public, anon;
grant execute on function public.is_admin() to anon, authenticated;

-- 4) Jogosultságok (explicit grant, az RLS további szűr) -----
grant usage on schema public to anon, authenticated;
grant select on public.news to anon, authenticated;
grant select, insert, update, delete on public.news to authenticated;
grant select on public.profiles to authenticated;

-- 5) RLS-szabályok (újrafuttatás: előbb töröljük a régit) ----
-- Bármelyik látogató olvashatja a híreket; csak admin módosíthatja.
drop policy if exists "Public can read news" on public.news;
create policy "Public can read news"
  on public.news for select
  to anon, authenticated
  using (true);

drop policy if exists "Admins can insert news" on public.news;
create policy "Admins can insert news"
  on public.news for insert
  to authenticated
  with check (public.is_admin());

drop policy if exists "Admins can update news" on public.news;
create policy "Admins can update news"
  on public.news for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "Admins can delete news" on public.news;
create policy "Admins can delete news"
  on public.news for delete
  to authenticated
  using (public.is_admin());

-- A felhasználó csak a SAJÁT profilját olvashatja.
-- A role értéket csak megbízható forrásból (SQL Editor) lehet módosítani,
-- ezért nincs insert/update policy a profiles táblán.
drop policy if exists "Users can read own profile" on public.profiles;
create policy "Users can read own profile"
  on public.profiles for select
  to authenticated
  using ((select auth.uid()) = id);

-- 6) Új felhasználókor automatikus profile-sor ------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, role)
  values (new.id, 'member')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

